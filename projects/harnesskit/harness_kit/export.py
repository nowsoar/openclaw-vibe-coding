"""Export utilities — AGENTS.md generation and MCP Server."""

from __future__ import annotations

import asyncio
from pathlib import Path
from typing import Any


# ---------------------------------------------------------------------------
# AGENTS.md generation
# ---------------------------------------------------------------------------

_AGENTS_MD_MAX_LINES = 60

_AGENTS_MD_HEADER = """\
# AGENTS.md — HarnessKit Skill Directory

> Auto-generated by `harnesskit export agents-md`. Do not edit manually.
> Regenerate after updating skills: `harnesskit export agents-md --output AGENTS.md`
"""

_AGENTS_MD_FOOTER = "---\n*Regenerate: `harnesskit export agents-md --output AGENTS.md`*\n"


def generate_agents_md(base: Path | None = None) -> str:
    """Generate an AGENTS.md document (≤60 lines) from registered Skills and Harnesses.

    Following the ETH Zurich research finding that AGENTS.md files exceeding 60 lines
    reduce agent performance, this function enforces a strict 60-line cap.

    Returns:
        Markdown string ready to write to AGENTS.md.
    """
    from harness_kit import skill as _skill_mod  # noqa: PLC0415
    from harness_kit import harness as _harness_mod  # noqa: PLC0415

    skills = _skill_mod.list_skills(base)
    harnesses = _harness_mod.list_harnesses(base)

    blocks: list[str] = [_AGENTS_MD_HEADER]

    # --- Skills section ---
    if skills:
        skill_lines: list[str] = ["## Skills\n"]
        for s in skills:
            name = s.get("name", "")
            desc = s.get("description", "")
            trigger = s.get("trigger", "")
            version = s.get("version", "")
            doc_path = f".harness/skills/{name}/{version}.yaml"
            if trigger:
                skill_lines.append(
                    f"- **{name}** (`{version}`): {desc}  \n"
                    f"  Trigger: _{trigger}_ | Docs: `{doc_path}`"
                )
            else:
                skill_lines.append(
                    f"- **{name}** (`{version}`): {desc} | Docs: `{doc_path}`"
                )
        blocks.append("\n".join(skill_lines) + "\n")

    # --- Harnesses section ---
    if harnesses:
        harness_lines: list[str] = ["## Harnesses\n"]
        for h in harnesses:
            name = h.get("name", "")
            desc = h.get("description", "")
            version = h.get("version", "")
            skill_refs = h.get("skills") or []
            skills_str = ", ".join(str(r) for r in skill_refs[:3])
            if len(skill_refs) > 3:
                skills_str += f" +{len(skill_refs) - 3} more"
            entry = f"- **{name}** (`{version}`): {desc}"
            if skills_str:
                entry += f"  \n  Skills: {skills_str}"
            harness_lines.append(entry)
        blocks.append("\n".join(harness_lines) + "\n")

    blocks.append(_AGENTS_MD_FOOTER)

    full_text = "\n".join(blocks)
    lines = full_text.splitlines()

    # Enforce ≤60 lines
    if len(lines) > _AGENTS_MD_MAX_LINES:
        truncated = lines[: _AGENTS_MD_MAX_LINES - 3]
        truncated += [
            "",
            "*(truncated — too many skills/harnesses to fit in 60 lines)*",
            "*Regenerate: `harnesskit export agents-md --output AGENTS.md`*",
        ]
        return "\n".join(truncated) + "\n"

    return full_text if full_text.endswith("\n") else full_text + "\n"


